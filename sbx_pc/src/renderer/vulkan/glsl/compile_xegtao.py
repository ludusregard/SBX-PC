"""Compiles Intel's XeGTAO (xegtao/XeGTAO.h and XeGTAO.hlsli, unmodified from
https://github.com/GameTechDev/XeGTAO, MIT) and the renderer's own XeGTAO
shaders into SPIR-V for the native renderer's --xegtao (passes.cpp,
ApplyXeGTAO), written to ../generated_xegtao.h. Checked in, so the build
needs no shader compiler; run from this directory after changing anything
here:

  python3 compile_xegtao.py

Needs glslangValidator (and spirv-val, if present, to check the result).

- xegtao/sbx_xegtao.hlsl: the compute kernels (in the place of the
  sample's vaGTAO.hlsl; its bindings are listed at its top).
- xegtao/xegtao_depth.comp: the AO's depth: the normals target's view
  distances over the view's depth (BuildDepthMotion) (NORMALS; with MULTISAMPLE for a
  multisampled normals target), or the view's depth alone.
- xegtao/xegtao_normals.comp: the materials' normals over the ones from depth
  (with MULTISAMPLE for a multisampled normals target).
- xegtao/xegtao_temporal.comp: the AO kept over frames (the history).
- xegtao/xegtao_apply.frag: the AO into the 3D view, under the light target's
  light (with MULTISAMPLE for a multisampled light target).
- xegtao/xegtao_debug.frag: --xegtao_debug's views.

XeGTAO.hlsli is patched on the way, as text, for glslang: integer literals
with a swizzle (`2.xx`, `1.xxxx`) become vector constructors
(`float2(2, 2)`), since glslang reads `2.` as a float and then fails on the
swizzle. And one change of ours: the plane bias's test in the main pass
(in patch(), below).
"""
import os
import re
import shutil
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE_DIR = os.path.join(HERE, 'xegtao')
OUT = os.path.join(HERE, '..', 'generated_xegtao.h')
TARGET = 'vulkan1.3'

# Name in the header, HLSL entry point.
KERNELS = [
    ('prefilter_depths', 'CSPrefilterDepths16x16'),
    ('generate_normals', 'CSGenerateNormals'),
    ('main_low', 'CSGTAOLow'),
    ('main_medium', 'CSGTAOMedium'),
    ('main_high', 'CSGTAOHigh'),
    ('main_ultra', 'CSGTAOUltra'),
    ('denoise', 'CSDenoisePass'),
    ('denoise_last', 'CSDenoiseLastPass'),
]

# Name in the header, GLSL file, defines.
GLSL_SHADERS = [
    ('depth_comp', 'xegtao_depth.comp', []),
    ('depth_normals_comp', 'xegtao_depth.comp', ['NORMALS']),
    ('depth_normals_ms_comp', 'xegtao_depth.comp', ['NORMALS', 'MULTISAMPLE']),
    ('normals_comp', 'xegtao_normals.comp', []),
    ('normals_ms_comp', 'xegtao_normals.comp', ['MULTISAMPLE']),
    ('temporal_comp', 'xegtao_temporal.comp', []),
    ('apply_frag', 'xegtao_apply.frag', []),
    ('apply_ms_frag', 'xegtao_apply.frag', ['MULTISAMPLE']),
    ('debug_frag', 'xegtao_debug.frag', []),
]


def patch(text):
    def vector(m):
        n = len(m.group(2))
        return 'float%d(%s)' % (n, ', '.join([m.group(1)] * n))

    text, count = re.subn(r'(?<![\w.])(\d+)\.(x{2,4})\b', vector, text)
    assert count == 4, count
    # SBX's plane bias (0.1 m, passes.cpp's XeGtao::plane_bias, in
    # GTAOConstants.Padding0, which XeGTAO doesn't use): a sample no higher
    # than the bias over the center's tangent plane (its normal: the
    # materials' smooth one, where written) doesn't occlude, fading in up to
    # twice the bias; so a step as small as a decal's (the course's road
    # markings) makes no AO where the surface's own normal says it's flat.
    anchor = '                // sample horizon cos\n'
    assert text.count(anchor) == 1
    text = text.replace(anchor, (
        '                if( consts.Padding0 > 0 )\n'
        '                {\n'
        '                    weight0 *= (lpfloat)saturate( dot( sampleDelta0, (float3)viewspaceNormal ) / consts.Padding0 - 1.0 );\n'
        '                    weight1 *= (lpfloat)saturate( dot( sampleDelta1, (float3)viewspaceNormal ) / consts.Padding0 - 1.0 );\n'
        '                }\n\n') + anchor)
    return text


def compile_spirv(cmd, spv, what):
    result = subprocess.run(cmd, capture_output=True, text=True)
    if result.returncode:
        sys.exit(f'{what}: ' + result.stdout + result.stderr)
    if shutil.which('spirv-val'):
        result = subprocess.run(['spirv-val', '--target-env', TARGET, spv],
                                capture_output=True, text=True)
        if result.returncode:
            sys.exit(f'{what}: ' + result.stdout + result.stderr)
    data = open(spv, 'rb').read()
    return list(struct.unpack(f'<{len(data) // 4}I', data))


def append_array(out, name, words):
    out.append(f'inline constexpr uint32_t k_xegtao_{name}[] = {{')
    for i in range(0, len(words), 8):
        out.append('    ' + ', '.join(f'0x{w:08x}' for w in words[i:i + 8]) + ',')
    out.append('};')
    out.append('')


def main():
    if not shutil.which('glslangValidator'):
        sys.exit('glslangValidator not found')
    out = ['// Generated by src/renderer/vulkan/glsl/compile_xegtao.py from xegtao/ (Intel\'s',
           '// XeGTAO, MIT: Copyright (C) 2016-2021, Intel Corporation, and the',
           '// renderer\'s own shaders); don\'t edit.',
           '#pragma once',
           '#include <cstdint>',
           '']
    with tempfile.TemporaryDirectory() as tmp:
        for name in ('XeGTAO.h', 'sbx_xegtao.hlsl'):
            shutil.copy(os.path.join(SOURCE_DIR, name), tmp)
        with open(os.path.join(SOURCE_DIR, 'XeGTAO.hlsli'), encoding='utf-8') as f:
            hlsli = patch(f.read())
        with open(os.path.join(tmp, 'XeGTAO.hlsli'), 'w', encoding='utf-8') as f:
            f.write(hlsli)
        src = os.path.join(tmp, 'sbx_xegtao.hlsl')
        for name, entry in KERNELS:
            spv = os.path.join(tmp, name + '.spv')
            cmd = ['glslangValidator', '-V', '-D', '-S', 'comp', '-e', 'main',
                   '--source-entrypoint', entry, '--target-env', TARGET, src, '-o', spv]
            append_array(out, name, compile_spirv(cmd, spv, entry))
        for name, file, defines in GLSL_SHADERS:
            spv = os.path.join(tmp, name + '.spv')
            cmd = ['glslangValidator', '-V', '--target-env', TARGET]
            cmd += ['-D' + d for d in defines] + [os.path.join(SOURCE_DIR, file), '-o', spv]
            append_array(out, name, compile_spirv(cmd, spv, file))
    with open(OUT, 'w', newline='\r\n') as f:
        f.write('\n'.join(out))
    print('written', os.path.normpath(OUT))


main()
